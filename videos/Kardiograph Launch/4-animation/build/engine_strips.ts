// engine_strips.ts: draws every tracing in this video with the real Kardiograph engine
// (marksuguitan/medzcool-kardiograph, src/core), so nothing on screen is a hand-made wave.
//   KARDIOGRAPH=/path/to/medzcool-kardiograph node --experimental-strip-types build/engine_strips.ts
// Writes remotion/src/data/engine.json: lead II at 250 Hz, in mV.
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const KG = process.env.KARDIOGRAPH ?? "/home/user/medzcool-kardiograph";
const { synthesizeCalibrated } = await import(path.join(KG, "src/core/calibrate.ts"));
const { PRESETS, applyPreset } = await import(path.join(KG, "src/core/presets.ts"));
const FS = 250;
const r3 = (v: number) => Math.round(v * 1000) / 1000;

function leadII(id: string, over: Record<string, number> = {}, seed = 7, durationS = 12) {
  const pr = PRESETS.find((p: any) => p.id === id);
  if (!pr) throw new Error(`no preset ${id}`);
  const r = synthesizeCalibrated({ ...applyPreset(pr), ...over, durationS }, seed);
  const s = r.signal;
  const step = Math.round(s.sampleRateHz / FS);
  const ii: number[] = [];
  for (let i = 0; i < s.leads.II.length; i += step) ii.push(r3(s.leads.II[i]));
  const onsets = s.beatOnsets.map((i: number) => r3(i / s.sampleRateHz));
  return { id, name: pr.name, II: ii, onsets, sampleRateHz: s.sampleRateHz };
}

// one beat, 300 ms before QRS onset to 600 ms after, for the QRS-width figure
function beat(qrsMs: number) {
  const s = leadII("normal", { qrsMs }, 7, 4);
  const on = s.onsets[1];
  const a = Math.round((on - 0.3) * FS);
  return { qrsMs, II: s.II.slice(a, a + Math.round(0.9 * FS)) };
}

const out = {
  note: "Generated by 4-animation/build/engine_strips.ts from the Kardiograph engine. Lead II, 250 Hz, mV. Do not edit by hand.",
  engineCommit: execSync("git rev-parse --short HEAD", { cwd: KG }).toString().trim(),
  fs: FS,
  strips: {
    normal: leadII("normal", {}, 7, 20),
    afib: leadII("afib", {}, 11),
    mobitz1: leadII("mobitz1", {}, 5),
    chb: leadII("chb", {}, 3),
    stemiInf: leadII("stemi-inf", {}, 9),
  },
  qrs: [90, 100, 110, 120, 130, 140, 150].map(beat),
};
const file = new URL("../remotion/src/data/engine.json", import.meta.url);
fs.writeFileSync(file, JSON.stringify(out));
console.log("wrote", file.pathname, "engine", out.engineCommit);
