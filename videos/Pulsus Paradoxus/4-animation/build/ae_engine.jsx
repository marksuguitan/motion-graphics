        var st = S.start + OFF;
        ml.startTime = st; ml.inPoint = st; ml.outPoint = st + S.dur;
        report.scenes_in_master.push({ scene: S.name, start: st, in_: ml.inPoint, out: ml.outPoint, comp_dur: ml.source ? ml.source.duration : -1 });
        var op = OP(ml);
        while (op.numKeys > 0) op.removeKey(1);
        op.setValue(100);
        if (S.xfade_in) keys(op, [[st, 0], [st + S.xfade_in, 100]]);
        if (S.fade_out) keys(op, [[st + S.dur - S.fade_out, 100], [st + S.dur, 0]]);
