"""Writes build_intro.jsx (After Effects) from intro_plan.json. Run from the Pulsus Paradoxus/build folder in AE:
File > Scripts > Run Script File. Rebuilds the 'Medzcool Intro' comp from scratch each run, saves the project
(previous copy in build/aep_backup) and renders check frames to build/ae_check/intro_*.png."""
import json, sys
P = json.load(open(sys.argv[1] if len(sys.argv) > 1 else "/tmp/claude-0/intro/intro_plan.json"))
out = sys.argv[2] if len(sys.argv) > 2 else "/tmp/claude-0/intro/build_intro.jsx"

JS = r"""#target aftereffects
// Medzcool logo intro (approved preview v3, Mark 2026-10-27). Generated by make_intro_jsx.py from intro_plan.json.
// Logo cut into a 40 px grid; tiles land on the first four lubs of the heartbeat (Normal S1 S2 (Apex).mp3 at 1.6x,
// ~120 bpm; S1/S2 measured); seams close on the 5th lub and one whole-logo layer takes over.
(function () {
    var P = __PLAN__;
    var proj = app.project;
    if (!proj || !proj.file) { alert("Open Pulsus Paradoxus.aep first."); return; }
    var buildDir = File($.fileName).parent.fsName, root = File($.fileName).parent.parent.fsName;
    var errs = [];
    function hex(h) { return [parseInt(h.substr(1, 2), 16) / 255, parseInt(h.substr(3, 2), 16) / 255, parseInt(h.substr(5, 2), 16) / 255]; }
    app.beginUndoGroup("Medzcool Intro");

    // folder + clean rebuild
    var fold = null;
    for (var i = 1; i <= proj.numItems; i++) if (proj.item(i) instanceof FolderItem && proj.item(i).name === "Intro") fold = proj.item(i);
    if (!fold) fold = proj.items.addFolder("Intro");
    // rebuild inside the existing comp (if any) so the master layer that uses it stays put
    var comp = null;
    for (var i2 = 1; i2 <= proj.numItems; i2++) { var it = proj.item(i2); if (it instanceof CompItem && it.name === P.name) comp = it; }
    if (comp) { while (comp.numLayers > 0) comp.layer(1).remove(); comp.duration = P.dur; comp.frameRate = P.fps; }
    else comp = proj.items.addComp(P.name, P.w, P.h, 1, P.dur, P.fps);
    comp.parentFolder = fold; comp.bgColor = hex(P.bg);
    var bg = comp.layers.addSolid(hex(P.bg), "Background", P.w, P.h, 1, P.dur);

    // audio
    var af = File(root + "/" + P.audio), foot = null;
    for (var a = 1; a <= proj.numItems; a++) { var ia = proj.item(a); if (ia instanceof FootageItem && ia.file && ia.file.fsName === af.fsName) foot = ia; }
    if (!foot) { try { foot = proj.importFile(new ImportOptions(af)); foot.parentFolder = fold; } catch (x) { errs.push("audio: " + x.toString()); } }
    if (foot) {
        var au = comp.layers.add(foot); au.name = "Heartbeat"; au.startTime = 0;
        var lv = au.property("ADBE Audio Group").property("ADBE Audio Levels");
        lv.setValueAtTime(P.fade[0], [0, 0]); lv.setValueAtTime(P.fade[1], [-48, -48]);
    }

    // pulse null
    var nul = comp.layers.addNull(P.dur); nul.name = "Pulse";
    nul.property("ADBE Transform Group").property("ADBE Anchor Point").setValue([50, 50]);
    nul.property("ADBE Transform Group").property("ADBE Position").setValue([P.w / 2, P.h / 2]);
    nul.property("ADBE Transform Group").property("ADBE Scale").expression =
        "// heartbeat pulse: +2.2% on lubs 2-4, +5% on the 5th (logo closes), +0.8% on each dub; exp decay\n" +
        "var S1 = " + "[" + P.S1.slice(1, 5).join(",") + "]" + ", S2 = " + "[" + P.S2.slice(0, 4).join(",") + "]" + ", F = " + P.final + ";\n" +
        "var v = 0, t = time;\n" +
        "for (var i = 0; i < S1.length; i++) if (t >= S1[i]) v += (S1[i] == F ? 0.05 : 0.022) * Math.exp(-(t - S1[i]) / 0.12) * Math.min(1, (t - S1[i]) / 0.04);\n" +
        "for (var j = 0; j < S2.length; j++) if (t >= S2[j]) v += 0.008 * Math.exp(-(t - S2[j]) / 0.1) * Math.min(1, (t - S2[j]) / 0.04);\n" +
        "[100 * (1 + v), 100 * (1 + v)];";

    function shapeLayer(name, paths, pos) {
        var L = comp.layers.addShape(); L.name = name;
        var g = L.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group"); g.name = "Logo";
        var vg = g.property("ADBE Vectors Group");
        for (var p = 0; p < paths.length; p++) {
            var sp = vg.addProperty("ADBE Vector Shape - Group");
            var s = new Shape(); s.vertices = paths[p]; s.closed = true;
            sp.property("ADBE Vector Shape").setValue(s);
        }
        var fl = vg.addProperty("ADBE Vector Graphic - Fill");
        fl.property("ADBE Vector Fill Color").setValue(hex(P.acc));
        var tr = L.property("ADBE Transform Group");
        tr.property("ADBE Anchor Point").setValue([0, 0]);
        tr.property("ADBE Position").setValue(pos);
        L.parent = nul;
        return L;
    }
    function keys(prop, arr, two) {
        var tt = [], vv = [];
        for (var k = 0; k < arr.length; k++) { tt.push(arr[k][0]); vv.push(two ? [arr[k][1], arr[k][1]] : arr[k][1]); }
        prop.setValuesAtTimes(tt, vv);
        for (var k2 = 1; k2 <= prop.numKeys; k2++) prop.setInterpolationTypeAtKey(k2, KeyframeInterpolationType.LINEAR);
    }

    // whole logo (takes over when the seams have closed)
    var full = shapeLayer("Logo_Full", P.full, [P.w / 2, P.h / 2]);
    full.inPoint = P.full_in; full.outPoint = P.dur;

    // tiles
    var made = 0;
    for (var t = 0; t < P.tiles.length; t++) {
        var T = P.tiles[t];
        try {
            var L = shapeLayer("Tile_" + T.id + "_b" + T.batch, T.paths, T.pos);
            var tr = L.property("ADBE Transform Group");
            keys(tr.property("ADBE Scale"), T.scale, true);
            keys(tr.property("ADBE Opacity"), T.opacity, false);
            L.inPoint = T.t0; L.outPoint = P.tile_out;
            made++;
        } catch (x) { errs.push(T.id + ": " + x.toString()); }
    }
    nul.moveToBeginning();
    bg.moveToEnd();

    // place at 0:00 of the master comp (Mark 2026-10-27: the intro opens the video). The first time, every master layer
    // moves P.dur later; the scene builds (engine OFF = PLAN.intro.dur) keep that offset from then on.
    var master = null, shifted = false;
    for (var mi = 1; mi <= proj.numItems; mi++) { var mc = proj.item(mi); if (mc instanceof CompItem && mc.name === P.master) master = mc; }
    if (master) {
        var il = null, s1 = null;
        for (var q = 1; q <= master.numLayers; q++) {
            var lq = master.layer(q);
            if (lq.source === comp) il = lq;
            if (lq.source && lq.source.name === "Scene 1") s1 = lq;
        }
        if (!il) {
            if (s1 && s1.startTime < 0.001) {
                master.duration = master.duration + P.dur;
                for (var q2 = 1; q2 <= master.numLayers; q2++) {
                    var L2 = master.layer(q2), lk = L2.locked; L2.locked = false; L2.startTime = L2.startTime + P.dur; L2.locked = lk;
                }
                shifted = true;
            }
            il = master.layers.add(comp);
        }
        il.startTime = 0; il.inPoint = 0; il.outPoint = P.dur; il.moveToEnd();
    } else errs.push("no master comp \"" + P.master + "\" in the project; intro not placed");
    comp.openInViewer();

    // save (previous copy kept)
    var aep = proj.file;
    if (!Folder(buildDir + "/aep_backup").exists) Folder(buildDir + "/aep_backup").create();
    aep.copy(File(buildDir + "/aep_backup/Pulsus Paradoxus " + new Date().getTime() + ".aep"));
    proj.save(aep);

    // check frames
    var chk = Folder(buildDir + "/ae_check"); if (!chk.exists) chk.create();
    var shots = 0;
    for (var c = 0; c < P.checks.length; c++) {
        var tc = P.checks[c], nm = "intro_" + (tc < 10 ? "0" : "") + tc.toFixed(2) + ".png";
        try { comp.saveFrameToPng(tc, File(chk.fsName + "/" + nm)); shots++; } catch (x) { errs.push("frame " + tc + ": " + x.toString()); }
    }
    var mshots = 0;
    if (master) for (var c2 = 0; c2 < P.master_checks.length; c2++) {
        var tm = P.master_checks[c2], ts = "0000" + tm.toFixed(2), nm2 = "master_" + ts.substr(ts.length - 7) + ".png";
        try { master.saveFrameToPng(tm, File(chk.fsName + "/" + nm2)); mshots++; } catch (x) { errs.push("master frame " + tm + ": " + x.toString()); }
    }
    app.endUndoGroup();

    var mlist = [];
    if (master) for (var mq = 1; mq <= master.numLayers; mq++) { var Lm = master.layer(mq); mlist.push('{"layer":"' + Lm.name + '","in":' + (Math.round(Lm.inPoint * 1000) / 1000) + ',"out":' + (Math.round(Lm.outPoint * 1000) / 1000) + "}"); }
    var rep = File(buildDir + "/intro_build_report.json"); rep.encoding = "UTF-8"; rep.open("w");
    var es = []; for (var e = 0; e < errs.length; e++) es.push('"' + String(errs[e]).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"');
    rep.write('{"comp":"' + P.name + '","tiles":' + made + ',"layers":' + comp.numLayers + ',"checks":' + shots + ',"master_checks":' + mshots + ',"shifted":' + shifted + ',"master_duration":' + (master ? master.duration : 0) + ',"master_layers":[' + mlist.join(",") + '],"errors":[' + es.join(",") + "]}");
    rep.close();
    alert("Medzcool Intro: built " + made + " tiles (" + comp.numLayers + " layers)" + (master ? ", placed at 0:00 of the master" + (shifted ? " (scenes moved " + P.dur + " s later)" : "") : "") + ". Errors: " + errs.length + ". Saved Pulsus Paradoxus.aep (previous copy in build/aep_backup); report in build/intro_build_report.json.");
})();
"""
open(out, "w").write(JS.replace("__PLAN__", json.dumps(P, separators=(",", ":"))))
print(out)
