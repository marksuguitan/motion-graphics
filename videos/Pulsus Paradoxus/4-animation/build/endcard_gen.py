"""Medzcool end card (call to action), approved preview v1 (Mark 2026-10-27) -> build_endcard.jsx for After Effects.
10 s, no VO. The logo lands on one heartbeat (lub 0.40 s, dub 0.60 s, measured from audio/cues/Heartbeat_endcard.wav, a
0.65 s cut of the intro's 120 bpm heartbeat delayed 0.18 s). Then, each fading in and rising 20 px: 'Thanks for watching'
(0.85 s), the subscribe line (1.05), the red SUBSCRIBE pill (1.25), 'WATCH NEXT' (1.45); the Watch-next slot outline
traces clockwise 1.6-2.2 s (room for a YouTube end-screen video element). Fade to black over the last 0.5 s.
The comp sits right after the last scene in the master. Keys are sampled per frame (linear) to match the preview."""
import json, math

W, H, FPS, DUR = 1920, 1080, 30, 10.0
BG, FG, ACC, GREY, DIM, LINE = "#151515", "#F2F2F2", "#FF4057", "#6E6E6E", "#BDBDBD", "#3A3B3C"
POLYS = [[13.98, 28.07, 4.31, 28.07, 0, 35.85, 18.54, 35.85, 23.46, 27.04, 34.59, 44.72, 38.86, 36.91, 23.06, 11.81],
         [61.63, 19.81, 50.85, 1.86, 41.25, 18.59, 29.55, 0, 25.33, 7.9, 41.56, 33.67, 51, 17.22, 57.23, 27.59, 65.77, 27.59, 69.66, 19.81]]
LX, LY, LWID = 160, 250, 300
LS = LWID / 69.66; LHGT = 44.72 * LS
LUB, DUB = 0.40, 0.60


def ob(x, s=2.0):
    x = min(max(x, 0), 1) - 1; return x * x * ((s + 1) * x + s) + 1


def oc(x):
    x = min(max(x, 0), 1); return 1 - (1 - x) ** 3


def frames(t0, t1):
    f = math.ceil(t0 * FPS - 1e-9); out = [round(t0, 4)]
    while f / FPS < t1 - 1e-9:
        if f / FPS > t0 + 1e-9: out.append(round(f / FPS, 4))
        f += 1
    out.append(round(t1, 4)); return out


# logo: pop (ease-out-back) from LUB-0.02 over 0.3 s, then a 1.2% pulse on the dub
cx, cy = LX + LWID / 2, LY + LHGT / 2
lg_scale = []
for t in frames(LUB - 0.02, 1.0):
    sc = ob((t - (LUB - 0.02)) / 0.3)
    if t >= DUB: sc *= 1 + 0.012 * math.exp(-(t - DUB) / 0.1) * min(1, (t - DUB) / 0.04)
    lg_scale.append([t, round(100 * sc, 3)])
lg_op = [[round(LUB - 0.02, 4), 0], [round(LUB + 0.04, 4), 100]]
logo = dict(paths=[[[round(p[i] * LS - LWID / 2, 3), round(p[i + 1] * LS - LHGT / 2, 3)] for i in range(0, len(p), 2)] for p in POLYS],
            pos=[round(cx, 3), round(cy, 3)], scale=lg_scale, opacity=lg_op)


def rise(t0):
    ks = frames(t0, t0 + 0.5)
    return [[t, round(100 * oc((t - t0) / 0.5), 2)] for t in ks], [[t, round(20 * (1 - oc((t - t0) / 0.5)), 3)] for t in ks]


items = []
for name, t0, kind, extra in (
        ("Title", 0.85, "text", dict(text="Thanks for watching", font="Helvetica-Bold", size=76, color=FG, x=LX - 4, base=561, track=0, just="left")),
        ("Subline", 1.05, "text", dict(text="Subscribe for more clinical explainers.", font="Helvetica", size=36, color=DIM, x=LX, base=629, track=0, just="left")),
        ("Subscribe_pill", 1.25, "pill", dict(x0=LX, y0=690, x1=LX + 300, y1=762, r=8, color=ACC)),
        ("Subscribe_text", 1.25, "text", dict(text="SUBSCRIBE", font="Helvetica-Bold", size=28, color="#FFFFFF", x=LX + 150, base=737, track=180, just="center")),
        ("Watch_next", 1.45, "text", dict(text="WATCH NEXT", font="Helvetica-Bold", size=24, color=GREY, x=1000, base=310, track=210, just="left"))):
    op, dy = rise(t0)
    items.append(dict(name=name, kind=kind, t0=t0, opacity=op, dy=dy, **extra))
slot_trim = [[t, round(100 * oc((t - 1.6) / 0.6), 3)] for t in frames(1.6, 2.2)]

plan = dict(name="Medzcool End Card", master="Pulsus Paradoxus", w=W, h=H, fps=FPS, dur=DUR, bg=BG, acc=ACC, line=LINE,
            audio="audio/cues/Heartbeat_endcard.wav", logo=logo, items=items,
            slot=dict(x0=1000, y0=336, x1=1760, y1=764, width=3, trim=slot_trim), fade=[DUR - 0.5, DUR],
            checks=[0.3, 0.42, 0.6, 1.0, 1.4, 1.9, 5.0, 9.8])
json.dump(plan, open("/tmp/claude-0/outro/endcard_plan.json", "w"))

